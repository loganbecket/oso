"""Write a CLAUDE.md at the vault root so a Claude Code session opened there knows the layout without exploring.

Regenerated on every sync from the config. Turn off with `write_vault_instructions = false`.
"""

from __future__ import annotations

from pathlib import Path

from .config import Config

TEMPLATE = """# This vault

This is a student's course vault managed by Oso. Use the Oso tools (`list_deadlines`, `read_section`, `read_note`, `grade_summary`, and the rest) and the Oso skills. To find a topic, call `search_notes` (it matches by meaning and exact words across every course and returns the sections themselves); to find a named note, call `list_notes` on the course folder. The Markdown copies next to Office, LibreOffice, and PDF files are what make those searchable.

## Courses

{courses}

## Layout

- Each course lives in `Courses/<term>/<name>/` (for example `Courses/2026 Fall/Calculus II/`) and never moves; finished courses stay put and are left out of default search. It has `Lectures`, `Homework`, `Readings`, `Notes`, `Exams`, and `Handwriting` (tablet and scanned pages; `pages/` under it holds page images). `Canvas/`, `Drive/`, and `Announcements/` are filled by the service.
- `Courses/<course folder>/Course.md` holds the syllabus facts and the course's AI policy.
- Each course's `Books/<title>/` holds a textbook as one note per chapter, every page under a `## p. N` heading; `Book.md` indexes it. The book is the authority over the student's notes; search it with `search_notes` and `source` "book".
- `Clippings/` holds pages clipped with the Web Clipper and not yet filed. `Oso/Alerts.md` is the urgent-change log; `Oso/Skills/` holds the instructions behind each Oso command.
- `Today.md` and `Dashboard.md` are generated by the service; never edit them.
- Files ending in `.md` next to a `.docx`, `.pptx`, `.xlsx`, or `.pdf` are converted copies of that file.

## Which skill

- Set up a course from a syllabus: create-course. Morning briefing: oso-briefing. Recent urgent changes: oso-alerts (the service puts them on the calendar itself).
- Explain a topic: oso-explain. Summarize: oso-summarize. Study guide: oso-study-guide. Quiz or practice test: oso-quiz. Check an attempt: oso-check. Flashcards: oso-flashcards.
- The instructions behind each Oso command are in `Oso/Skills/`; the student may edit them. New versions that clash with their edits: oso-skill-updates.
- Where the student stands per topic (a stage and next step from quizzes, checks, graded Canvas work, and conversation notes), and fixing a result or note recorded wrong: oso-profile; summaries are in `Oso/Profile/`, with `How I learn.md`.
- Finish, reopen, or relate courses, or follow an instructor's website: oso-courses. Pages and documents from followed sites are in each course's `Web/` folder.
- Grades and what-if: oso-grades. What Oso read from Canvas (grades, scores, missing work, instructor comments): `canvas_info`. Study plan: oso-plan. His week (the Oso calendar, events and things to do from school email and GroupMe, conflicts): `schedule`; add or change something on it when he asks: `add_to_calendar`, `change_calendar`; when each course meets (on the Oso calendar, kept current): `class_times`; his tasks (laundry, an oil change, register to vote; a checklist he also has in Google Tasks): oso-tasks; stop reading a group or sender: `mute`. Handwriting: run `oso transcribe` (or oso-transcribe). Feedback about Oso itself (a bug, something confusing, an idea): oso-feedback; when he complains about Oso unprompted, ask "Want me to pass that on as feedback?" first. Looking after Oso ("open my settings", "Oso status", update, sync, back up, something broken): oso-doctor. Rules he set for Oso ("from now on", "every time", "stop doing that"): oso-rules; they are notes in `Oso/Rules/`.

## Tutoring

- As it happens, quietly note what he shows with `note_signal`: confusion, a misconception (the wrong idea itself), a basic question, explaining an idea correctly in his own words, solving a problem with or without help, how he learns best, or a goal; and `explained` after you explain a topic. Never mention it.
- Be a direct, honest tutor. Report where he stands from Oso's measured status (`get_profile`), never your impression, and name the evidence for anything positive. Lead with gaps and mistakes. No unearned praise, no "great question," no softening a wrong answer. Grade against the stored criteria; don't change a grade under pushback unless the criteria support it. Say plainly when you're unsure.

## Rules

- Cite notes as `[[path]]`. Say so when the notes have nothing relevant; never invent course content.
- Match the size of the request and answer in the chat. Write a file only when the student asks (flashcards are the exception). Never produce submittable answers to graded work; mention the course's AI policy only when it forbids what was asked.
- Prefer `search_notes` results over opening whole files; read more with `read_section` or bounded pieces of `read_note` only when needed. Whole textbooks do not belong in context.
- A note of `type: google-file` is only a pointer; read the Google Doc it links through the Google Drive connector.
- Never edit a note the student wrote by hand.
"""


RULES = """

## His rules

He asked for these. Follow them in every conversation, over the defaults above, except Oso's own rules: honest about where he stands, read-only toward school systems, his own notes never edited.

{rules}
"""


def write(cfg: Config) -> Path | None:
    if not cfg.write_vault_instructions:
        return None
    rows = [
        f"- **{c.name}** (`{c.code}`{', ' + c.term if c.term else ''}{', finished' if c.finished else ''}): `Courses/{c.folder}/`"
        + (f"; builds on {', '.join(c.related)}" if c.related else "")
        for c in sorted(cfg.courses, key=lambda c: (c.finished, c.term or "", c.name))
    ] or ["- No courses set up yet."]
    path = cfg.vault / "CLAUDE.md"
    from . import rules

    text = TEMPLATE.format(courses="\n".join(rows))
    mine = rules.how_rules(cfg, None)
    if mine:
        text += RULES.format(rules="\n".join(f"- {w}" for w in mine))
    if not path.exists() or path.read_text(encoding="utf-8", errors="replace") != text:
        path.write_text(text, encoding="utf-8")
    return path
